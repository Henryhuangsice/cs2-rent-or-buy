// 输入守卫：先于模型执行，命中即终止或附加警告。
const BLOCK = [
  { id: 'credential', re: /(api\s*key|apikey|密钥|密码|令牌|验证码).{0,12}(给|发|填|输入|交|告诉|要)|(给|发|填|输入|交出|索要|要我).{0,12}(api\s*key|apikey|密钥|密码|令牌|验证码)/i,
    msg: '任何人索要 Steam 密码、令牌或 API Key 都应视为诈骗。不要提供；如果已经泄露，请立即改密码、撤销 API Key 并检查交易记录。' },
  { id: 'abuse', re: /(怎么|如何|能不能|可以).{0,10}(白嫖|不归还|赖账|骗|绕过风控|套现|刷补贴|撤回.{0,6}(骗|白拿))/, msg: '这个请求可能损害其他用户或违反平台规则，我不提供做法。可以帮你查询正常的归还和撤销规则。' },
  { id: 'invest', re: /(会涨|会跌|涨吗|跌吗|能赚|赚钱|理财|投资|抄底|升值|囤货)/, msg: '我不预测饰品价格，也不给投资建议。我可以按你的使用天数比较租和买的使用成本，并展示涨跌情景。' },
];
export function guard(text) {
  if (text.length > 500) return { id: 'too_long', msg: '输入过长，请用一两句话说明饰品、使用天数和预算。' };
  return BLOCK.find((b) => b.re.test(text)) ?? null;
}
